#!/usr/bin/env python3
"""Rasterize fonts into 1-bit bitmaps for the e-paper renderer. Usage: genfont.py > font_data.c
Fonts: Barlow Condensed Bold (SIL OFL, big numbers/labels) and DejaVu Sans Mono Bold (small text)."""
import sys, os
from PIL import Image, ImageDraw, ImageFont
here = os.path.dirname(os.path.abspath(__file__))
BARLOW = os.path.join(here, "BarlowCondensed-Bold.ttf")
MONO = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
DIG = "0123456789,-'"
BAR = "0123456789-.kM"
HDR = "0123456789,-'+"
LAB = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .·"
SMALL = "".join(chr(c) for c in range(32, 127)) + "▲▼◄·!"
# (c name, ttf, px, chars, mono_hinted)
FONTS = [(f"F_NUM{p}", BARLOW, p, DIG, False) for p in (103, 90, 78, 63, 52, 44)] + [
    ("F_PRIME", BARLOW, 47, "'", False),
    ("F_BAR27", BARLOW, 27, BAR, False), ("F_BAR22", BARLOW, 22, BAR, False),
    ("F_HDR33", BARLOW, 33, HDR, False), ("F_HDR18", BARLOW, 18, HDR, False),
    ("F_ROW25", BARLOW, 25, LAB, False), ("F_ROW22", BARLOW, 22, LAB, False), ("F_ROW18", BARLOW, 18, LAB, False),
    ("F_SMALL", MONO, 10, SMALL, True),
]
out = ['// Generated by tools/genfont.py. Do not edit.', '#include "font.h"', '']
tables = []
for name, ttf, px, chars, mono in FONTS:
    f = ImageFont.truetype(ttf, px)
    asc, desc = f.getmetrics()
    bits = bytearray(); glyphs = []
    for ch in chars:
        l, t, r, b = f.getbbox(ch, anchor="ls")
        w, h = max(r - l, 0), max(b - t, 0)
        adv = int(round(f.getlength(ch)))
        off = len(bits)
        if w and h:
            im = Image.new("L" if not mono else "1", (w, h), 0)
            d = ImageDraw.Draw(im)
            if mono: d.fontmode = "1"
            d.text((-l, -t), ch, font=f, fill=255 if not mono else 1, anchor="ls")
            px_ = im.load()
            for y in range(h):
                row = 0; n = 0
                for x in range(w):
                    on = px_[x, y] >= 110 if not mono else px_[x, y]
                    row = (row << 1) | (1 if on else 0); n += 1
                    if n == 8: bits.append(row); row = 0; n = 0
                if n: bits.append(row << (8 - n))
        glyphs.append((ord(ch), w, h, l, t, adv, off))
    glyphs.sort()
    out.append(f"static const uint8_t {name}_bits[] = {{" + ",".join(str(b) for b in bits) + "};")
    out.append(f"static const Glyph {name}_g[] = {{" + ",".join("{%d,%d,%d,%d,%d,%d,%d}" % g for g in glyphs) + "};")
    out.append(f"const Font {name} = {{ {name}_g, {len(glyphs)}, {name}_bits, {asc}, {px} }};")
    out.append("")
print("\n".join(out))
